import AppKit
import CryptoKit
import QNotchMacCore

/// Text and images you copy, kept in memory (Windows ClipboardModule). macOS has no pasteboard
/// change notification, so a 1-second timer compares `changeCount` (an integer read; contents are
/// read only after a change). This is the one deliberate repeating wake while the module is on.
/// Content marked concealed or transient (password managers) is never captured; images are never saved.
final class ClipboardModule: NotchModule {
    private var context: ModuleContext!
    private(set) var history = ClipHistory()
    private(set) var settings = ClipboardSettings()
    private var watch: Timer?
    private var ages: Timer?
    private var lastChange = NSPasteboard.general.changeCount
    private var ownWrite: Int?
    private let io = DispatchQueue(label: "qnotch.clipboard", qos: .utility)
    private let views = NSHashTable<AnyObject>.weakObjects()
    private(set) var denied = false
    private(set) var checks = 0
    var filter: ClipKind? { didSet { refresh() } }
    private var historyURL: URL { context.settings.directory.appendingPathComponent("clipboard.json") }

    /// Markers from nspasteboard.org that apps (1Password, Bitwarden, Keychain Access…) set on secrets.
    static let skipped: Set<NSPasteboard.PasteboardType> = [
        .init("org.nspasteboard.ConcealedType"), .init("org.nspasteboard.TransientType"),
        .init("org.nspasteboard.AutoGeneratedType"), .init("com.agilebits.onepassword"),
        .init("com.typeit4me.clipping"), .init("de.petermaurer.TransientPasteboardType"), .init("Pasteboard generator type")
    ]

    func initialize(_ context: ModuleContext) {
        self.context = context
        settings = context.settings.load("clipboard", default: ClipboardSettings())
        if settings.keepHistory { loadHistory() }
        context.registries.cards.register(ViewContribution(id: "clipboard", title: "Clipboard", order: 30, symbol: "doc.on.clipboard") { [unowned self] in
            self.track(ClipboardCardView(module: self))
        })
        context.registries.tabs.register(ViewContribution(id: "clipboard", title: "Clipboard", order: 20, symbol: "doc.on.clipboard") { [unowned self] in
            self.track(ClipboardTabView(module: self))
        })
        context.registries.searchSources.register(SearchSource(id: "clipboard", order: 10) { [weak self] query in
            guard let self else { return [] }
            return self.history.search(query).map { entry in
                SearchHit(title: entry.line, detail: "\(entry.meta) · copies it", symbol: Self.symbol(entry.kind)) { [weak self] in
                    self?.copyAgain(entry)
                    self?.context.shell?.closePanel()
                }
            }
        })
        context.registries.settingsSections.register(ViewContribution(id: "clipboard", title: "Clipboard", order: 30, symbol: "doc.on.clipboard", tint: .systemIndigo) { [weak self] in
            self?.makeSettings() ?? NSView()
        })
        startWatching()
    }

    private func track<V: NSView & ClipboardDisplay>(_ view: V) -> NSView {
        views.add(view)
        view.reload()
        return view
    }

    func setVisibility(panel: Bool, activeTab: String) {
        // "5m ago" texts refresh every 30 s only while the Clipboard tab is on screen.
        let showAges = panel && activeTab == "clipboard"
        if showAges, ages == nil {
            let timer = Timer(timeInterval: 30, repeats: true) { [weak self] _ in self?.refresh() }
            timer.tolerance = 5
            RunLoop.main.add(timer, forMode: .common)
            ages = timer
            refresh()
        } else if !showAges {
            ages?.invalidate(); ages = nil
        }
        if !panel { ClipboardImages.shared.removeAll() }
    }

    func systemDidWake() { check() }
    func stop() { watch?.invalidate(); watch = nil; ages?.invalidate(); ages = nil }

    // MARK: Watching

    private func startWatching() {
        if #available(macOS 15.4, *), NSPasteboard.general.accessBehavior == .alwaysDeny {
            denied = true
            return
        }
        let timer = Timer(timeInterval: 1, repeats: true) { [weak self] _ in self?.check() }
        timer.tolerance = 0.5
        RunLoop.main.add(timer, forMode: .common)
        watch = timer
    }

    private func check() {
        let pasteboard = NSPasteboard.general
        let change = pasteboard.changeCount
        checks += 1
        guard change != lastChange else { return }
        lastChange = change
        guard change != ownWrite else { return }
        if #available(macOS 15.4, *), pasteboard.accessBehavior == .alwaysDeny {
            denied = true
            stop()
            refresh()
            return
        }
        capture(pasteboard)
    }

    /// Text first, else an image. Finder file copies, concealed and transient content are skipped.
    func capture(_ pasteboard: NSPasteboard) {
        guard let types = pasteboard.types, !types.contains(where: Self.skipped.contains), !types.contains(.fileURL) else { return }
        if types.contains(.string), let data = pasteboard.data(forType: .string), data.count <= ClipText.maxTextLength * 4,
           let text = String(data: data, encoding: .utf8), let entry = ClipText.entry(text) {
            add(entry)
            return
        }
        guard let raw = pasteboard.data(forType: .png) ?? pasteboard.data(forType: .tiff), raw.count <= 34 << 20 else { return }
        io.async { [weak self] in
            guard let entry = Self.imageEntry(raw) else { return }
            DispatchQueue.main.async { self?.add(entry) }
        }
    }

    private static func imageEntry(_ raw: Data) -> ClipEntry? {
        guard let rep = NSBitmapImageRep(data: raw), let png = rep.representation(using: .png, properties: [:]),
              png.count <= 4 << 20 else { return nil }
        let key = SHA256.hash(data: png.prefix(1 << 20)).prefix(12).map { String(format: "%02x", $0) }.joined() + "-\(png.count)"
        let meta = "Image · \(rep.pixelsWide)×\(rep.pixelsHigh) · \(ClipText.size(png.count))"
        return ClipEntry(kind: .image, text: nil, png: png, key: key, preview: "", line: "Image \(rep.pixelsWide)×\(rep.pixelsHigh)", meta: meta, created: Date())
    }

    private func add(_ entry: ClipEntry) {
        history.add(entry)
        changed()
    }

    // MARK: Actions

    func copyAgain(_ entry: ClipEntry) {
        let pasteboard = NSPasteboard.general
        pasteboard.clearContents()
        if let text = entry.text { pasteboard.setString(text, forType: .string) }
        else if let png = entry.png {
            pasteboard.setData(png, forType: .png)
            if let tiff = NSImage(data: png)?.tiffRepresentation { pasteboard.setData(tiff, forType: .tiff) }
        }
        ownWrite = pasteboard.changeCount
        lastChange = ownWrite ?? lastChange
        history.add(entry.with(created: Date()))
        changed()
    }

    func remove(_ entry: ClipEntry) { history.remove(entry.id); changed() }
    func togglePin(_ entry: ClipEntry) { history.togglePin(entry.id); changed() }
    func clear() { history.clearUnpinned(); changed() }

    private func changed() {
        refresh()
        if settings.keepHistory { saveHistory() }
    }

    func refresh() { for case let view as ClipboardDisplay in views.allObjects { view.reload() } }

    // MARK: Persistence (text only, opt-in)

    private struct Saved: Codable {
        struct Item: Codable { var text: String; var pinned: Bool; var created: Date }
        var items: [Item]
    }

    private func saveHistory() {
        let saved = Saved(items: history.persistable.map { Saved.Item(text: $0.text ?? "", pinned: $0.pinned, created: $0.created) })
        let url = historyURL, directory = context.settings.directory
        io.async {
            guard let data = try? JSONEncoder().encode(saved) else { return }
            try? FileManager.default.createDirectory(at: directory, withIntermediateDirectories: true)
            try? data.write(to: url, options: .atomic)
        }
    }

    private func loadHistory() {
        guard let data = try? Data(contentsOf: historyURL), data.count < 16 << 20,
              let saved = try? JSONDecoder().decode(Saved.self, from: data) else { return }
        var restored = ClipHistory()
        for item in saved.items.reversed() {
            guard var entry = ClipText.entry(item.text, at: item.created) else { continue }
            entry.pinned = item.pinned
            restored.add(entry)
        }
        history = restored
    }

    private func setKeepHistory(_ value: Bool) {
        settings.keepHistory = value
        context.settings.save("clipboard", settings)
        if value { saveHistory() } else { io.async { [url = historyURL] in try? FileManager.default.removeItem(at: url) } }
    }

    // MARK: Settings

    private func makeSettings() -> NSView {
        let width = SettingsController.contentWidth
        let keep = ActionSwitch("Keep history between sessions", value: settings.keepHistory) { [weak self] value in self?.setKeepHistory(value) }
        let clear = NSButton(title: "Clear History", target: nil, action: nil)
        clear.bezelStyle = .rounded
        let clearAction = ClosureTarget { [weak self] in self?.clear() }
        clear.target = clearAction
        clear.action = #selector(ClosureTarget.run)
        objc_setAssociatedObject(clear, "action", clearAction, .OBJC_ASSOCIATION_RETAIN)
        var rows = [
            settingsRow("Keep history between sessions", detail: "Saves text entries and pins to clipboard.json on this Mac. Images are never saved. Turning this off deletes the file.", control: keep, width: width),
            settingsRow("Clear history", detail: "Removes every entry except pinned ones. History holds the last 40 entries.", control: clear, width: width)
        ]
        if denied {
            rows.append(settingsRow("Access denied", detail: "macOS denies QNotch access to the clipboard. Allow it in System Settings, Privacy & Security, Paste from Other Apps, then turn Clipboard history off and on.", width: width))
        }
        return settingsGroup(rows, footer: "QNotch checks whether the clipboard changed once a second and reads it only after a change. Anything a password manager marks as concealed or transient, Finder file copies, and anything copied again from QNotch are never captured. macOS may ask once whether QNotch may read the clipboard.", width: width)
    }

    static func symbol(_ kind: ClipKind) -> String {
        switch kind {
        case .text: return "text.alignleft"
        case .link: return "link"
        case .code: return "chevron.left.forwardslash.chevron.right"
        case .image: return "photo"
        }
    }
}

extension ClipEntry {
    func with(created date: Date) -> ClipEntry {
        var copy = self
        copy.created = date
        return copy
    }
}

/// Decoded image previews, kept only while the panel is open.
final class ClipboardImages {
    static let shared = ClipboardImages()
    private var cache: [UUID: NSImage] = [:]
    func image(_ entry: ClipEntry) -> NSImage? {
        if let image = cache[entry.id] { return image }
        guard let png = entry.png, let image = NSImage(data: png) else { return nil }
        cache[entry.id] = image
        return image
    }
    func removeAll() { cache.removeAll() }
}

/// Target-action adapter for a closure.
final class ClosureTarget: NSObject {
    private let handler: () -> Void
    init(_ handler: @escaping () -> Void) { self.handler = handler }
    @objc func run() { handler() }
}
